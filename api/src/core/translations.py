def language_of(req: func.HttpRequest) -> str:
    """O idioma do cookie da requisição; ausente, malformado ou desconhecido vale o padrão."""
    header = req.headers.get("Cookie") or ""
    for part in header.split(";"):
        name, _, value = part.strip().partition("=")
        if name == LANGUAGE_COOKIE:
            chosen = value.strip().lower()
            return chosen if chosen in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE
    return DEFAULT_LANGUAGE


def cookie_header(language: str, *, secure: bool) -> str:
    """O ``Set-Cookie`` que lembra o idioma: ``HttpOnly`` e ``Secure`` quando a requisição é HTTPS."""
    attributes = [
        f"{LANGUAGE_COOKIE}={language}",
        "Path=/",
        f"Max-Age={COOKIE_MAX_AGE_SECONDS}",
        "SameSite=Lax",
        "HttpOnly",
    ]
    if secure:
        attributes.append("Secure")
    return "; ".join(attributes)


def key_of(text: str) -> str:
    """A chave de busca: espaços colapsados e pontas aparadas, como o protótipo normalizava."""
    return " ".join(text.split())


def translate(namespace: str, text: str, language: str) -> str:
    """A tradução de ``text`` no idioma pedido: em português devolve o texto intacto.

    Em inglês procura no namespace do módulo e, sem achar, no ``comum``; sem
    tradução em lugar nenhum devolve o texto original (nunca vazio, nunca
    inventado). Traduzir tradução não acontece: só a chave em português está no
    catálogo.
    """
    if language != EN or not text:
        return text
    lookup = key_of(text)
    table = CATALOG.get(namespace, {})
    if lookup in table:
        return table[lookup]
    return CATALOG["comum"].get(lookup, text)


t = translate


def closure(language: str):
    """O ``t`` que entra no contexto dos fragmentos: ``{{ t('financeiro', 'Resumo') }}``."""

    def _t(namespace: str, text: str) -> str:
        return translate(namespace, text, language)

    return _t


