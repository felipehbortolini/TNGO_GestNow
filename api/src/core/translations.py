MESES_CURTOS: dict[str, tuple[str, ...]] = {
    "pt": ("jan", "fev", "mar", "abr", "mai", "jun", "jul", "ago", "set", "out", "nov", "dez"),
    "en": ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"),
}

DATE_FORMATS = {"pt": "%d/%m/%Y", "en": "%m/%d/%Y"}


def mes_curto(month: int, language: str) -> str:
    """O mês curto do idioma: ``set`` em português, ``Sep`` em inglês."""
    names = MESES_CURTOS.get(language, MESES_CURTOS[DEFAULT_LANGUAGE])
    return names[(month - 1) % 12]


def format_date(value: date | datetime | None, language: str) -> str:
    """A data no formato do idioma (``25/09/2026`` ou ``09/25/2026``); ``None`` é vazio."""
    if value is None:
        return ""
    return value.strftime(DATE_FORMATS.get(language, DATE_FORMATS[DEFAULT_LANGUAGE]))


def date_formatter(language: str):
    """O ``data`` do contexto dos fragmentos: ``{{ data(valor) }}`` no idioma do request."""

    def _format(value: date | datetime | None) -> str:
        return format_date(value, language)

    return _format


def datetime_formatter(language: str):
    """O ``data_hora`` do contexto: data do idioma e hora de 24 h."""

    def _format(value: date | datetime | None) -> str:
        if value is None:
            return ""
        pattern = DATE_FORMATS.get(language, DATE_FORMATS[DEFAULT_LANGUAGE])
        return value.strftime(f"{pattern} %H:%M")

    return _format


